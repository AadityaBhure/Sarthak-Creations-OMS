import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

test('numbering migration, old/deleted backfill, independent serials, duplicate confirmation and irreversible allocation', { skip: !process.env.PGLITE_MODULE }, async () => {
  const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE).href);
  const db = new PGlite();
  const sql = file => readFile(new URL('../supabase/migrations/' + file, import.meta.url), 'utf8');
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE TABLE orders(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),date_of_entry date,po_number text,client_id uuid,product_name_id uuid,product_type_id uuid,quantity integer CHECK(quantity>0),status text DEFAULT 'Design Confirmed',remark text,executive_id uuid,target_date date,assignment_history text,created_at timestamptz DEFAULT now(),updated_at timestamptz DEFAULT now());
      CREATE TABLE deleted_orders(LIKE orders INCLUDING DEFAULTS); ALTER TABLE deleted_orders ADD PRIMARY KEY(id); ALTER TABLE deleted_orders ADD deleted_at timestamptz DEFAULT now();
      GRANT ALL ON orders,deleted_orders TO service_role;
      INSERT INTO orders(id,po_number,created_at,status) VALUES('00000000-0000-0000-0000-000000000001','old-active','2026-01-02','Design Confirmed'),('00000000-0000-0000-0000-000000000002','old-completed','2026-01-03','Completed');
      INSERT INTO deleted_orders(id,po_number,created_at) VALUES('00000000-0000-0000-0000-000000000003','old-deleted','2026-01-01');
      CREATE TABLE global_settings(id text primary key,recycle_retention_days integer); INSERT INTO global_settings VALUES('default',10);
      CREATE TABLE activity_logs(user_id uuid,username text,action text,module text,record_id uuid,details jsonb);
      CREATE SCHEMA cron; CREATE FUNCTION cron.schedule(text,text,text) RETURNS bigint LANGUAGE sql AS $$ SELECT 1::bigint $$;`);
    await db.exec(await sql('20260927_vendor_job_tracking.sql'));
    await db.exec(await sql('20260928_vendor_job_repair_and_master_recycle.sql'));
    await db.exec((await sql('20260929_vendor_job_deleted_records.sql')).replace('CREATE EXTENSION IF NOT EXISTS pg_cron;', ''));
    const master = async kind => (await db.query('SELECT vjt_save_master($1,null,$2) r', [kind, { name: kind }])).rows[0].r.after.id;
    const vendor = await master('vendors'), job = await master('jobs'), paper = await master('papers');
    const newCard = async () => (await db.query("SELECT vjt_mutate('create',null,$1) r", [{ quantity: 20, vendor_id: vendor, job_type_id: job, paper_type_id: paper }])).rows[0].r.after;
    const oldCard = await newCard();
    await db.query("SELECT vjt_mutate('delete',$1,$2)", [oldCard.id, { revision: oldCard.revision }]);
    const migration = await sql('20261028_order_numbering.sql');
    await db.exec(migration); await db.exec(migration);
    assert.deepEqual((await db.query('SELECT serial_number,order_number FROM orders ORDER BY created_at')).rows, [{ serial_number: 2, order_number: null }, { serial_number: 3, order_number: null }]);
    assert.equal((await db.query('SELECT serial_number FROM deleted_orders')).rows[0].serial_number, 1);
    assert.equal((await db.query("SELECT record FROM vjt_deleted_records WHERE kind='cards'")).rows[0].record.serial_number, 1);
    const save = async (id, data, confirm = false, expected = null) => (await db.query('SELECT oms_save_order($1,$2,$3,$4) r', [id, data, confirm, expected])).rows[0].r;
    const next = async () => (await db.query('SELECT oms_order_defaults() r')).rows[0].r.order_number;
    await db.exec('SET ROLE service_role');
    const ten = await save(null, { po_number: 'unchanged-po', order_number: 10, quantity: 2 });
    assert.equal(ten.serial_number, 4); assert.equal(await next(), 11);
    const eleven = await save(null, { quantity: 2 }, false, 11);
    assert.equal(eleven.order_number, 11); assert.equal(eleven.serial_number, 5);
    await save(ten.id, { order_number: 50 }); assert.equal(await next(), 12);
    await assert.rejects(save(null, { quantity: 2 }, false, 11), /suggested Order Number changed/);
    await assert.rejects(save(null, { order_number: 11, quantity: 2 }), /already been used/);
    const duplicate = await save(null, { order_number: 11, quantity: 2 }, true);
    assert.equal(duplicate.serial_number, 6); assert.equal(await next(), 12);
    await assert.rejects(save(ten.id, { order_number: 11 }), /already been used/);
    await save(ten.id, { order_number: 11 }, true); assert.equal(await next(), 12);
    await assert.rejects(db.query('UPDATE orders SET serial_number=100 WHERE id=$1', [ten.id]), /cannot be changed/);
    await assert.rejects(save(ten.id, { serial_number: 100 }), /cannot be edited/);
    await assert.rejects(db.exec('UPDATE oms_number_counters SET last_serial=0'), /permission denied/);
    // Existing soft-delete/restore APIs copy all columns. Serial and order number survive unchanged.
    const elevenSnapshot = (await db.query('SELECT * FROM orders WHERE id=$1', [eleven.id])).rows[0];
    await db.query('INSERT INTO deleted_orders SELECT (jsonb_populate_record(NULL::deleted_orders,$1)).*', [{ ...elevenSnapshot, deleted_at: new Date().toISOString() }]);
    await db.query('DELETE FROM orders WHERE id=$1', [eleven.id]);
    assert.equal(await next(), 12);
    await db.query('INSERT INTO orders SELECT (jsonb_populate_record(NULL::orders,$1)).*', [elevenSnapshot]);
    await db.query('DELETE FROM deleted_orders WHERE id=$1', [eleven.id]);
    assert.equal((await db.query('SELECT serial_number FROM orders WHERE id=$1', [eleven.id])).rows[0].serial_number, 5);
    assert.equal(await next(), 12);
    await db.query('DELETE FROM orders WHERE id=$1', [duplicate.id]);
    const twelve = await save(null, { quantity: 2 }); assert.equal(twelve.serial_number, 7); assert.equal(twelve.order_number, 12);
    await assert.rejects(save(null, { order_number: 200, quantity: -1 }), /check constraint/);
    assert.equal(await next(), 13);
    const card = await newCard(); assert.equal(card.serial_number, 2);
    await assert.rejects(db.query('UPDATE vjt_job_cards SET serial_number=90 WHERE id=$1', [card.id]), /cannot be changed/);
    await db.query("SELECT vjt_mutate('purge',$1,$2)", [oldCard.id, { revision: 2 }]);
    assert.equal((await newCard()).serial_number, 3);
    await db.exec('RESET ROLE');
    await db.exec(migration);
    assert.equal(await next(), 13);
    assert.equal((await save(null, { order_number: 100, quantity: 2 })).serial_number, 8);
    assert.equal(await next(), 101);
  } finally { await db.close(); }
});

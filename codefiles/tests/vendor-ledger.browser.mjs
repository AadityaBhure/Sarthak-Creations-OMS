// Isolated localhost server with test JWT; every business endpoint is mocked.
import { pathToFileURL } from 'node:url';
import { SignJWT } from 'jose';
import assert from 'node:assert/strict';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const base = process.env.TEST_BASE_URL || 'http://localhost:3104';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw Error('Local test server only');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  context.setDefaultTimeout(15000);
  const token = await new SignJWT({ role: 'admin', username: 'Test only' }).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('10m').sign(new TextEncoder().encode('vendor-job-local-test-secret'));
  await context.addCookies([{ name: 'session', value: token, url: base }]);
  const id = n => `00000000-0000-0000-0000-${String(n).padStart(12, '0')}`;
  const masters = { vendors: [{ id: id(1), name: 'Vendor A' }, { id: id(2), name: 'Vendor B', deleted_at: '2026-10-28' }, { id: id(3), name: 'Vendor C' }], jobs: [{ id: id(4), name: 'Printing' }, { id: id(5), name: 'Cutting' }], papers: [], products: [] };
  const row = (n, vendorId, vendor, stage, job, deleted = false) => ({ id: id(100+n), vendor_id: vendorId, vendor, job_type_id: job === 'Printing' ? id(4) : id(5), job_type: job, stage_number: stage, stage_started_at: '2026-10-29T09:00:00Z', serial_number: 1, job_card_number: 'JB0001', job_title: 'Gift boxes', quantity: 500, status: 'Completed', paper_type: 'Art', product_type: 'Carton', deleted_at: deleted ? '2026-10-29T10:00:00Z' : null });
  const rows = [row(1,id(1),'Vendor A',1,'Printing'), row(2,id(2),'Vendor B',2,'Cutting'), row(3,id(1),'Vendor A',3,'Cutting'), { ...row(4,id(2),'Vendor B',1,'Printing',true), job_card_number: 'JB0002', serial_number: 2 }, ...Array.from({length:26}, (_,i) => ({ ...row(10+i,id(3),'Vendor C',1,'Printing'), job_card_number:'JB'+(10+i), serial_number:10+i }))];
  let setupFail = false;
  const searches = [];
  await context.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname;
    const reply = (data, status = 200) => route.fulfill({ status, json: data });
    if (path === '/api/settings') return reply({ default_pagination: 25 });
    if (path === '/api/vendor-jobs/masters') return reply(masters);
    if (path === '/api/quick-views') return reply([]);
    if (path === '/api/vendor-jobs/ledger') {
      const input = route.request().postDataJSON(); searches.push(input);
      if (setupFail) return reply({ error: 'Run 20261029_vendor_ledger.sql in Supabase SQL Editor.', code: 'SETUP_REQUIRED' },503);
      let found = rows.filter(r => (!input.vendorId || r.vendor_id === input.vendorId) && (input.includeDeleted || !r.deleted_at));
      for (const f of input.filters) if (f.value) found = found.filter(r => String(r[f.column]) === f.value);
      const count = found.length;
      found = found.slice((input.page-1)*input.limit,input.page*input.limit);
      return reply({ data: found, meta: { totalRowCount: count } });
    }
    return reply({ error: 'Unexpected test request' },500);
  });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const select = async (label, text) => { await page.getByRole('combobox',{name:label,exact:true}).fill(text); await page.getByRole('option',{name:text,exact:true}).click(); };
  await page.goto(base+'/vendor-jobs/ledger');
  await page.getByText('Showing 1 to 25 of 29', {exact:true}).first().waitFor();
  await page.getByRole('button',{name:'Next',exact:true}).first().click();
  await page.getByText('Showing 26 to 29 of 29', {exact:true}).first().waitFor();
  await select('Ledger Vendor','Vendor A');
  await page.getByText('Showing 1 to 2 of 2',{exact:true}).first().waitFor();
  assert.equal(searches.at(-1).page,1);
  assert.equal(await page.getByRole('cell',{name:'JB0001',exact:true}).count(),2);
  await page.getByRole('cell',{name:'Printing',exact:true}).waitFor();
  await page.getByRole('cell',{name:'Cutting',exact:true}).waitFor();
  await page.getByLabel('Select visit 3 of JB0001',{exact:true}).check();
  const pending = page.waitForEvent('download');
  await page.getByRole('button',{name:'Export CSV',exact:true}).click();
  const download = await pending; const stream = await download.createReadStream();
  let csv=''; for await(const chunk of stream) csv+=chunk.toString();
  assert.equal(download.suggestedFilename(),'vendor-ledger.csv');
  assert.equal(csv.split('\r\n').length,2); assert.ok(csv.includes('Cutting') && !csv.includes('Printing') && csv.includes('Stage Date / Time'));
  await page.getByRole('button',{name:'+ Add Filter Rule',exact:true}).click();
  await select('Filter field 1','Work / Job Type');
  await select('Filter value 1','Printing');
  await page.getByText('Showing 1 to 1 of 1',{exact:true}).first().waitFor();
  assert.equal(searches.at(-1).filters[0].column,'job_type_id');
  await page.getByRole('button',{name:'Clear All',exact:true}).click();
  await select('Ledger Vendor','Vendor B (Deleted)');
  await page.getByText('Showing 1 to 1 of 1',{exact:true}).first().waitFor();
  await page.getByLabel('Include Job Cards in Deleted Records',{exact:true}).check();
  await page.getByText('Showing 1 to 2 of 2',{exact:true}).first().waitFor();
  await page.getByRole('cell',{name:'JB0002',exact:true}).waitFor();
  await page.getByRole('button',{name:/Stage No\./}).click();
  await page.getByText('Showing 1 to 2 of 2',{exact:true}).first().waitFor();
  await page.screenshot({path:process.env.TEMP+'/vendor-ledger.png',fullPage:true});
  setupFail=true;
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'20261029_vendor_ledger.sql'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Export CSV',exact:true}).isDisabled(),true);
  setupFail=false;
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.getByRole('cell',{name:'JB0002',exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: repeated visits, vendor selection, deleted vendors/cards, pagination, stage filters, selected CSV and setup retry');
} finally { await browser.close(); }
